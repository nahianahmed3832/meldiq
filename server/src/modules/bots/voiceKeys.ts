import {
  createHash,
  createPublicKey,
  diffieHellman,
  generateKeyPairSync,
} from "node:crypto";
import { badRequest } from "../../shared/errors.js";

/** Public X25519 material only. A low-order point must not be approved as a media recipient. */
export function validateBotVoicePublicKey(
  value: string | null | undefined,
): void {
  if (value == null) return;
  try {
    const raw = Buffer.from(value, "base64");
    if (raw.length !== 32 || raw.toString("base64") !== value)
      throw new Error("Malformed key");
    const publicKey = createPublicKey({
      key: Buffer.concat([Buffer.from("302a300506032b656e032100", "hex"), raw]),
      format: "der",
      type: "spki",
    });
    diffieHellman({
      privateKey: generateKeyPairSync("x25519").privateKey,
      publicKey,
    });
  } catch {
    throw badRequest(
      "Enter a valid public X25519 encryption key generated by your bot",
    );
  }
}

export function botVoiceFingerprint(
  publicKey: string | null | undefined,
): string | null {
  return publicKey
    ? createHash("sha256")
        .update(Buffer.from(publicKey, "base64"))
        .digest("hex")
    : null;
}
