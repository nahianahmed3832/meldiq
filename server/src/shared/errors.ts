/**
 * The API's error type and its uniform envelope `{ error: { code, message, details? } }`, written by the error handler
 * in app/server.ts (docs/architecture/ARCHITECTURE_1_0_PLAN.md §4).
 *
 * ERROR_CODES is the catalog of every code a client can receive, with the HTTP statuses it comes with and what it
 * means; `ApiError` only takes codes from it, so a new code has to be added here (and is then documented for every
 * client). `meaning` is the usual message; the message a response carries can be more specific. Codes that federated
 * servers send each other are not client-facing and not listed.
 */
export interface ErrorSpec {
  readonly status: readonly number[];
  readonly meaning: string;
}

