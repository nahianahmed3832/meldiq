"""Renders the logo used in account emails from the app's logo, brand/meldling.png: the off-white Meldling face on its
deep teal, 128x128 (shown at 40x40, sharp on high-density screens), rounded corners, PNG. Writes
server/src/infrastructure/mail/mailLogo.ts with the PNG as base64, so the API image needs no extra files.

Run after replacing the logo (needs Pillow):
    python3 -I server/scripts/render-mail-logo.py
"""
import base64
import io
import os

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SIZE = 128
RADIUS = 28  # about 22% of the side, like the app's tile
SCALE = 4  # draw the corner mask larger, then shrink it, for smooth edges

logo = Image.open(os.path.join(ROOT, "brand", "meldling.png")).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
mask = Image.new("L", (SIZE * SCALE, SIZE * SCALE), 0)
ImageDraw.Draw(mask).rounded_rectangle((0, 0, SIZE * SCALE - 1, SIZE * SCALE - 1), radius=RADIUS * SCALE, fill=255)
logo.putalpha(mask.resize((SIZE, SIZE), Image.LANCZOS))
clean = Image.new("RGBA", logo.size)  # a fresh image carries no colour profile or other metadata
clean.paste(logo)

out = io.BytesIO()
clean.save(out, format="PNG", optimize=True)
data = base64.b64encode(out.getvalue()).decode("ascii")
lines = [data[i:i + 116] for i in range(0, len(data), 116)]
body = "\n".join(f'  "{line}" +' for line in lines)[:-2]

target = os.path.join(ROOT, "server", "src", "infrastructure", "mail", "mailLogo.ts")
with open(target, "w") as f:
    f.write("// Generated by server/scripts/render-mail-logo.py from brand/meldling.png. Don't edit by hand.\n\n")
    f.write(f"/** The Meldiq logo for account emails: PNG, {SIZE}x{SIZE}, rounded corners, base64. */\n")
    f.write("export const MAIL_LOGO_PNG_BASE64 =\n")
    f.write(body + ";\n")
print(f"{target}: {len(out.getvalue())} bytes of PNG")
