import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { VERSION } from "../src/app/server.js";
import { ROUTE_CONTRACTS } from "../src/shared/contracts/http/index.js";
import { buildOpenApi, buildRealtimeSchema } from "../src/shared/contracts/openapi.js";
import { ServerEvent } from "../src/shared/contracts/realtime.js";
import { BotGatewayClientFrame, BotGatewayServerFrame } from "../src/shared/contracts/botGateway.js";
import { z } from "zod/v4";

/** Writes docs/api/openapi.json and docs/api/realtime.schema.json from src/shared/contracts. */
export const API_DOCS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "docs", "api");

const FIXTURES = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "shared", "contracts", "fixtures");

/** The fixture name of a route (test/support/contracts.ts writes the same). */
export const fixtureName = (method: string, url: string): string =>
  `${method} ${url}`.replace(/[/:]+/g, "_").replace(/\s+/g, "").replace(/_+/g, "_").replace(/^_|_$/g, "");

/**
 * Which documented routes and frames the test suite has really seen answered (a golden fixture exists): their schemas
 * are verified against the server; the others are documented from the code only.
 */
function coverage(): string {
  const seen = (rel: string) => fs.existsSync(path.join(FIXTURES, rel));
  const routes = ROUTE_CONTRACTS.map((c) => ({ c, ok: c.binary === "response" || seen(`http/${fixtureName(c.method, c.url)}.json`) }));
  const frames = ServerEvent.options.flatMap((o) => {
    // The nested call union has no shape of its own: its frames are named by event.
    const t = "shape" in o ? (o.shape as { t?: { value?: string } }).t?.value : undefined;
    return t ? [t] : ["call.ring", "call.started", "call.updated", "call.ended", "call.declined", "call.dismissed", "call.alerted", "call.moderated"];
  });
  const lines = [
    "# Contract coverage",
    "",
    "Generated by `npm run contracts` (do not edit). A route or frame is **verified** when the server test suite has seen",
    "a real answer that matched its schema (a golden fixture exists in `shared/contracts/fixtures`); the others are",
    "documented from the code and still need a test that exercises them.",
    "",
    `Routes: ${routes.filter((r) => r.ok).length} of ${routes.length} verified. Frames: ${frames.filter((f) => seen(`realtime/${f}.json`)).length} of ${frames.length} verified.`,
    "",
    "| Route | Area | Verified |",
    "|---|---|---|",
    ...routes.map(({ c, ok }) => `| \`${c.method} ${c.url}\` | ${c.tag} | ${ok ? "yes" : "**no**"} |`),
    "",
    "| Frame | Verified |",
    "|---|---|",
    ...frames.map((f) => `| \`${f}\` | ${seen(`realtime/${f}.json`) ? "yes" : "**no**"} |`),
    "",
  ];
  return lines.join("\n");
}

export function renderContracts(): Record<string, string> {
  return {
    "openapi.json": `${JSON.stringify(buildOpenApi(VERSION), null, 2)}\n`,
    "realtime.schema.json": `${JSON.stringify(buildRealtimeSchema(), null, 2)}\n`,
    "bot-gateway.schema.json": `${JSON.stringify({ version: 1, client: z.toJSONSchema(BotGatewayClientFrame), server: z.toJSONSchema(BotGatewayServerFrame) }, null, 2)}\n`,
    "COVERAGE.md": coverage(),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.mkdirSync(API_DOCS, { recursive: true });
  for (const [name, text] of Object.entries(renderContracts())) fs.writeFileSync(path.join(API_DOCS, name), text);
  process.stdout.write(`wrote ${Object.keys(renderContracts()).join(", ")} to docs/api\n`);
}
