/**
 * Renders Meldiq's own profile decorations (docs/PROFILE_DECORATIONS.md) from scripts/decorations/: each to
 * assets/decorations/<id>.webp (animated WebP when it moves), the submission template to
 * assets/decorations/template.png, and the list the server serves to src/modules/accounts/decorations/builtins.generated.ts.
 * Nothing here runs in the server: it ships the files. Run after changing the art:
 *   node scripts/render-decorations.mjs [--only id,id] [--sheet preview.png [--sheet-only]]
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { CLASSIC } from "./decorations/classic.mjs";
import { MORE } from "./decorations/more.mjs";
import { C, R, S } from "./decorations/shapes.mjs";

const root = path.resolve(import.meta.dirname, "..");
const outDir = path.join(root, "assets/decorations");
/** Output side: sharp on a 2× screen at the largest size the apps draw a decoration (about 120 px). */
const OUT = 256;
const FRAME_MS = 100;

const args = process.argv.slice(2);
const only = args.includes("--only") ? new Set(args[args.indexOf("--only") + 1].split(",")) : null;
const sheet = args.includes("--sheet") ? args[args.indexOf("--sheet") + 1] : null;
/** Only the preview sheet: no files written. */
const sheetOnly = args.includes("--sheet-only");

const ALL = [...CLASSIC, ...MORE];
const ids = new Set();
for (const d of ALL) {
  if (!/^[a-z0-9-]{2,32}$/.test(d.id) || ids.has(d.id)) throw new Error(`bad or repeated id ${d.id}`);
  ids.add(d.id);
}

const frame = (d, t) => sharp(Buffer.from(d.draw(t))).resize(OUT, OUT).png().toBuffer();

fs.mkdirSync(outDir, { recursive: true });
for (const d of sheetOnly ? [] : ALL) {
  if (only && !only.has(d.id)) continue;
  const file = path.join(outDir, `${d.id}.webp`);
  if (d.frames > 1) {
    const frames = [];
    for (let i = 0; i < d.frames; i++) frames.push(await frame(d, i / d.frames));
    await sharp(frames, { join: { animated: true } })
      .webp({ loop: 0, delay: Array(d.frames).fill(FRAME_MS), quality: 72, effort: 4 })
      .toFile(file);
  } else {
    await sharp(await frame(d, 0)).webp({ quality: 85, effort: 4 }).toFile(file);
  }
  console.log(d.id, fs.statSync(file).size);
}

// The submission template: the avatar's circle and the strip above the name, as guides on a see-through square.
const template = `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}" viewBox="0 0 ${S} ${S}">
  <rect x="1" y="1" width="${S - 2}" height="${S - 2}" fill="none" stroke="#8a8f98" stroke-width="2" stroke-dasharray="10 8"/>
  <circle cx="${C}" cy="${C}" r="${R}" fill="#8a8f98" fill-opacity="0.35" stroke="#ff7a5c" stroke-width="3" stroke-dasharray="12 8"/>
  <rect x="96" y="${S - 40}" width="${S - 192}" height="36" rx="8" fill="#ff7a5c" fill-opacity="0.18"/>
  <text x="${C}" y="${C - 8}" text-anchor="middle" font-family="DejaVu Sans, Arial, sans-serif" font-size="26" fill="#ffffff">The avatar goes here:</text>
  <text x="${C}" y="${C + 26}" text-anchor="middle" font-family="DejaVu Sans, Arial, sans-serif" font-size="26" fill="#ffffff">keep it empty</text>
  <text x="${C}" y="${S - 16}" text-anchor="middle" font-family="DejaVu Sans, Arial, sans-serif" font-size="18" fill="#ffd2c4">keep this strip light</text>
</svg>`;
if (!only && !sheetOnly) await sharp(Buffer.from(template)).png({ compressionLevel: 9 }).toFile(path.join(outDir, "template.png"));

if (!sheetOnly) writeList();
function writeList() {
const list = ALL.map((d) => `  { id: ${JSON.stringify(d.id)}, name: ${JSON.stringify(d.name)}, animated: ${d.frames > 1} },`).join("\n");
fs.writeFileSync(
  path.join(root, "src/modules/accounts/decorations/builtins.generated.ts"),
  `// Generated by \`node scripts/render-decorations.mjs\` from scripts/decorations/: do not edit.\n` +
    `/** Meldiq's own decorations, in the order the apps show them; each image is assets/decorations/<id>.webp. */\n` +
    `export const BUILTIN_DECORATIONS: readonly { id: string; name: string; animated: boolean }[] = [\n${list}\n];\n`,
);
}

if (sheet) {
  // Every decoration's first frame over a sample avatar, to look at.
  const cell = 170;
  const cols = 8;
  const shown = ALL.filter((d) => !only || only.has(d.id));
  const rows = Math.ceil(shown.length / cols);
  const avatar = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${cell}" height="${cell}"><circle cx="${cell / 2}" cy="${cell / 2 - 15}" r="${(130 * R) / S}" fill="#e6a540"/><text x="${cell / 2}" y="${cell / 2 - 3}" text-anchor="middle" font-family="Arial" font-weight="bold" font-size="34" fill="#fff">N</text></svg>`);
  const layers = [];
  for (const [i, d] of shown.entries()) {
    const left = (i % cols) * cell;
    const top = Math.floor(i / cols) * cell;
    layers.push({ input: avatar, left, top });
    layers.push({ input: await sharp(Buffer.from(d.draw(0.3))).resize(130, 130).png().toBuffer(), left: left + 20, top: top + 5 });
    layers.push({ input: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${cell}" height="24"><text x="${cell / 2}" y="17" text-anchor="middle" font-family="Arial" font-size="15" fill="#ddd">${d.name}</text></svg>`), left, top: top + cell - 26 });
  }
  await sharp({ create: { width: cols * cell, height: rows * cell, channels: 4, background: "#2b2d31" } }).composite(layers).png().toFile(sheet);
  console.log("sheet", sheet);
}

// Art cut off by the canvas edge: anything opaque in the outermost pixels of a still frame (moving particles may cross it).
if (args.includes("--check-edges")) {
  for (const d of ALL.filter((x) => x.frames === 1)) {
    const { data, info } = await sharp(Buffer.from(d.draw(0))).raw().toBuffer({ resolveWithObject: true });
    let hits = 0;
    for (let y = 0; y < info.height; y++)
      for (let x = 0; x < info.width; x++) if ((x < 2 || y < 2 || x >= info.width - 2 || y >= info.height - 2) && data[(y * info.width + x) * 4 + 3] > 40) hits++;
    if (hits) console.log("touches the edge:", d.id, hits);
  }
}
